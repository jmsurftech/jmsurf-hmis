export function searchIcd11(q?: string, limit = 25) {
  if (!q?.trim()) return ICD11_CODES.slice(0, limit);
  const terms = q.toLowerCase().split(/\s+/).filter(Boolean);
  return ICD11_CODES.map((c) => {
    const hay = `${c.code} ${c.title} ${c.icd10 ?? ''}`.toLowerCase();
    if (!terms.every((t) => hay.includes(t))) return null;
    const score = (c.code.toLowerCase() === q.toLowerCase() ? 100 : 0) + (c.code.toLowerCase().startsWith(terms[0]) ? 50 : 0) + (c.title.toLowerCase().startsWith(terms[0]) ? 20 : 0);
    return { c, score };
  })
    .filter((x): x is { c: (typeof ICD11_CODES)[number]; score: number } => !!x)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.c);
}
